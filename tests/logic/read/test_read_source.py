def test_read_source_a_binary_file_is_skipped(tmp_path) -> None:
    """A NUL byte is the mark of binary content; no size is reported for it."""
    path = _write(tmp_path, "image.bin", b"\x00\x01\x02\x03")

    report, text = read_source(path, tmp_path, None)

    assert report == FileReport(path, "image.bin", "skipped", "not a text file")
    assert text is None


def test_read_source_text_that_is_not_valid_utf8_at_the_start_is_skipped(tmp_path) -> None:
    """The first bytes decide whether it looks like text."""
    path = _write(tmp_path, "latin.txt", b"\xff\xfe\xfd text")

    report, text = read_source(path, tmp_path, None)

    assert (report.status, report.reason, text) == ("skipped", "not a text file", None)


@pytest.mark.parametrize("kind", ["missing", "directory"])
def test_read_source_a_path_that_is_not_a_file_is_skipped_not_raised(tmp_path, kind) -> None:
    """Nothing is raised for it: it is simply not a text file."""
    path = tmp_path / "nothing"
    if kind == "directory":
        path.mkdir()

    report, text = read_source(path, tmp_path, None)

    assert (report.status, report.reason, text) == ("skipped", "not a text file", None)


def test_read_source_an_output_of_the_library_is_skipped(tmp_path) -> None:
    """The marker in the first lines says the file was generated."""
    path = _write(tmp_path, "extraction.md", f"<!-- {GENERATED_MARKER} -->\nbody\n".encode())

    report, text = read_source(path, tmp_path, None)

    assert report.status == "skipped"
    assert report.reason == "generated by simplibs-extractor"
    assert report.bytes_in == path.stat().st_size
    assert text is None


def test_read_source_the_marker_is_looked_for_in_the_first_lines_only(tmp_path) -> None:
    """A file that merely mentions the marker later on is an ordinary file."""
    lines = ["line"] * MARKER_SCAN_LINES + [GENERATED_MARKER]
    path = _write(tmp_path, "notes.txt", ("\n".join(lines) + "\n").encode())

    report, text = read_source(path, tmp_path, None)

    assert report.status == "ok"
    assert text is not None


def test_read_source_the_marker_on_the_last_scanned_line_counts(tmp_path) -> None:
    """The scan covers exactly `MARKER_SCAN_LINES` lines."""
    lines = ["line"] * (MARKER_SCAN_LINES - 1) + [GENERATED_MARKER]
    path = _write(tmp_path, "out.md", ("\n".join(lines) + "\n").encode())

    report, _ = read_source(path, tmp_path, None)

    assert report.reason == "generated by simplibs-extractor"


def test_read_source_a_generated_file_is_recognized_before_the_size_limit(tmp_path) -> None:
    """Outputs are usually large; they should be named for what they are, not for their size."""
    path = _write(tmp_path, "extraction.md", f"{GENERATED_MARKER}\n{'x' * 500}\n".encode())

    report, _ = read_source(path, tmp_path, 10)

    assert report.reason == "generated by simplibs-extractor"


@pytest.mark.parametrize(
    "max_size, status",
    [(None, "ok"), (100, "ok"), (10, "ok"), (9, "skipped")],
    ids=["no-limit", "plenty", "exactly-the-size", "one-byte-too-small"],
)
def test_read_source_the_size_limit_is_inclusive(tmp_path, max_size, status) -> None:
    """A file of exactly the allowed size is still read."""
    path = _write(tmp_path, "a.txt", b"0123456789")

    report, text = read_source(path, tmp_path, max_size)

    assert report.status == status
    assert (text is None) == (status == "skipped")


def test_read_source_a_file_that_is_too_large_says_how_large(tmp_path) -> None:
    """The reason carries both numbers."""
    path = _write(tmp_path, "big.txt", b"x" * 50)

    report, text = read_source(path, tmp_path, 20)

    assert report == FileReport(path, "big.txt", "skipped", "too large (50 > 20 bytes)", 50)
    assert text is None


