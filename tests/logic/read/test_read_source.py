def test_read_source_text_that_breaks_after_the_checked_start_is_an_error_not_a_crash(tmp_path) -> None:
    """The first 8 KB look like UTF-8; the read of the whole file then fails. The run continues."""
    path = _write(tmp_path, "late.txt", b"a" * 9000 + b"\xff\xfe")

    report, text = read_source(path, tmp_path, None)

    assert report.status == "error"
    assert report.reason.startswith("read failed: ")
    assert "\n" not in report.reason
    assert text is None


def test_read_source_an_os_error_while_reading_is_an_error_report(tmp_path, monkeypatch) -> None:
    """A file that is locked, or that vanished after the checks."""
    path = _write(tmp_path, "a.txt", b"x")

    def broken_read(*args, **kwargs):
        raise OSError("disk gone")

    monkeypatch.setattr(MODULE, "read_text", broken_read)

    report, text = read_source(path, tmp_path, None)

    assert report == FileReport(path, "a.txt", "error", "read failed: OSError: disk gone")
    assert text is None


def test_read_source_a_card_while_reading_is_an_error_report_in_one_line(tmp_path, monkeypatch) -> None:
    """A card of the ecosystem prints as a framed block; the report keeps one line of it."""
    path = _write(tmp_path, "a.txt", b"x")

    def broken_read(*args, **kwargs):
        raise_source_not_found_error(Path("a.txt"))

    monkeypatch.setattr(MODULE, "read_text", broken_read)

    report, text = read_source(path, tmp_path, None)

    assert report.status == "error"
    assert report.reason.startswith("read failed: NotFoundError: ")
    assert "\n" not in report.reason
    assert text is None


def test_read_source_an_error_that_is_not_about_the_file_is_not_hidden(tmp_path, monkeypatch) -> None:
    """A bug in the code is not a file that failed to read."""
    path = _write(tmp_path, "a.txt", b"x")

    def broken_read(*args, **kwargs):
        raise RuntimeError("a bug")

    monkeypatch.setattr(MODULE, "read_text", broken_read)

    with pytest.raises(RuntimeError):
        read_source(path, tmp_path, None)


def test_read_source_one_failed_file_does_not_affect_the_next_one(tmp_path) -> None:
    """Each call stands alone."""
    bad = _write(tmp_path, "bad.txt", b"a" * 9000 + b"\xff")
    good = _write(tmp_path, "good.txt", b"fine")

    assert read_source(bad, tmp_path, None)[0].status == "error"
    assert read_source(good, tmp_path, None)[0].status == "ok"


# ---------------------------------------------------------------- symbolic links

import pytest as _pytest


def _link(link: Path, target: Path) -> None:
    try:
        link.symlink_to(target)
    except (OSError, NotImplementedError):
        _pytest.skip("symbolic links are not available here")


def test_a_link_leading_outside_the_source_is_skipped_under_its_own_name(tmp_path) -> None:
    root = tmp_path / "project"
    root.mkdir()
    secret = tmp_path / "outside" / "secret.txt"
    secret.parent.mkdir()
    secret.write_text("TOP SECRET\n", encoding="utf-8")
    link = root / "link.txt"
    _link(link, secret)

    report, text = read_source(link, root, None)

    assert report.status == "skipped"
    assert report.reason == "points outside the source"
    assert report.relative == "link.txt"
    assert text is None


def test_a_link_that_stays_inside_the_source_is_followed(tmp_path) -> None:
    root = tmp_path / "project"
    root.mkdir()
    (root / "real.txt").write_text("hello\n", encoding="utf-8")
    link = root / "link.txt"
    _link(link, root / "real.txt")

    report, text = read_source(link, root, None)

    assert report.status == "ok"
    assert report.relative == "link.txt"
    assert text == "hello\n"


def test_a_broken_link_is_never_an_ok_file(tmp_path) -> None:
    root = tmp_path / "project"
    root.mkdir()
    link = root / "dangling.txt"
    _link(link, tmp_path / "does-not-exist.txt")

    report, text = read_source(link, root, None)

    assert report.status in {"skipped", "error"}
    assert text is None
