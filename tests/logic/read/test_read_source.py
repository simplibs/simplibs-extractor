import sys
from pathlib import Path
import pytest
from simplibs.extractor.constants import GENERATED_MARKER, MARKER_SCAN_LINES
from simplibs.extractor.definitions import FileReport
from simplibs.extractor.logic.select._validations import raise_source_not_found_error
from simplibs.extractor.logic.read import read_source

# `simplibs.extractor.logic.read.read_source` is also the name of the function, so the MODULE is taken from `sys.modules`.
MODULE = sys.modules["simplibs.extractor.logic.read.read_source"]


def _write(root: Path, relative: str, data: bytes) -> Path:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return path


# ----------------------------------------------------------------------
# A file that is read
# ----------------------------------------------------------------------

def test_read_source_a_text_file_is_ok_and_its_text_comes_back(tmp_path) -> None:
    """The report says `ok` and carries the size; the text is the second value."""
    path = _write(tmp_path, "a.txt", "hello\n".encode())

    report, text = read_source(path, tmp_path, None)

    assert report == FileReport(path, "a.txt", "ok", None, 6)
    assert text == "hello\n"


def test_read_source_the_size_is_counted_in_bytes_not_characters(tmp_path) -> None:
    """`příliš` is six characters and eight bytes in UTF-8."""
    path = _write(tmp_path, "cz.txt", "příliš".encode("utf-8"))

    report, text = read_source(path, tmp_path, None)

    assert text == "příliš"
    assert report.bytes_in == 9


def test_read_source_an_empty_file_is_an_ok_file_with_an_empty_text(tmp_path) -> None:
    """Empty is text by convention."""
    path = _write(tmp_path, "empty.txt", b"")

    report, text = read_source(path, tmp_path, None)

    assert (report.status, report.bytes_in, text) == ("ok", 0, "")


@pytest.mark.parametrize("relative", ["a.txt", "sub/b.txt", "sub/deeper/c.txt", "s p a c e s/d.txt"])
def test_read_source_the_relative_path_uses_forward_slashes(tmp_path, relative) -> None:
    """The report shows the same path on every system."""
    path = _write(tmp_path, relative, b"x")

    report, _ = read_source(path, tmp_path, None)

    assert report.relative == relative
    assert report.path == path


