from typing import Literal


FileStatus = Literal["ok", "skipped", "error"]
"""The outcome of one file: included in the output, left out on purpose, or failed."""


_DESIGN_NOTES = """
# FileStatus — Three Outcomes, Nothing Else

## Purpose
`skipped` is not a failure (binary file, too large, generated by this
library) and `error` is not a stop (the run continues). Keeping the two apart
is what lets the report and the exit code tell "nothing wrong" from "something
needs a look".
"""
