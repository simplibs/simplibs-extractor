from typing import Literal


FileStatus = Literal["ok", "partial", "skipped", "error"]
"""The outcome of one file: included whole, included but not fully processed, left out on purpose, or failed."""


_DESIGN_NOTES = """
# FileStatus — Four Outcomes, Nothing Else

## Purpose
`skipped` is not a failure (binary file, too large, generated by this
library), `partial` is not a failure either (the file is in the output, but a
step could not process it fully), and `error` is not a stop (the run
continues). Keeping them apart is what lets the report and the exit code tell
"nothing wrong" from "something needs a look".

## `partial` Is in the Output
A partial file entered the output with the text the steps left it with; the
report says why. It is the answer to a file that a step cannot handle (a
Python 2 source for a Python parser, say): dropping it would hide it, and
failing the run would punish all the other files.

## How a File Becomes `partial`
A step that cannot handle a file returns the text unchanged and warns
(`warnings.warn(...)`, a `UserWarning`). The extractor collects the warnings
of the steps of one file; the file is `partial` and the reason is the text of
the warning. A step that raises makes the file `error`, as before.
"""
