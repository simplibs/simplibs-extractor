from pathlib import Path
from simplibs.exception import SimpleException
from simplibs.file import file_size, is_text_file, read_text
from simplibs.path import normalize_path, relativize_path
# Outers
from ...definitions import FileReport
from .._common import describe_failure
# Inners
from .is_generated_file import is_generated_file


def read_source(
    path: Path,
    root: Path,
    max_size: int | None,
) -> tuple[FileReport, str | None]:
    """Read one file into an extraction, or say why it stays out.

    The checks run cheapest first: binary file, generated output, size, and
    only then the read itself.

    Args:
        path: The absolute path of the file.
        root: The source folder (the base of the relative path in the report).
        max_size: The largest allowed size in bytes; `None` switches the limit off.

    Returns:
        A pair: the report of the file, and its text (`None` unless the status is `ok`).
        A file that cannot be read is reported as `error`; nothing is raised for it.
    """

    # 1. The path as the report and the output will show it (lexically: a link keeps its own name)
    try:
        relative = path.relative_to(root).as_posix()
    except ValueError:
        relative = relativize_path(path, root=root).as_posix()

    try:
        # 2. A link that leads out of the source is never followed: what it points at is not part of the project
        if not normalize_path(path).is_relative_to(normalize_path(root)):
            return FileReport(path, relative, "skipped", "points outside the source"), None

        # 3. Binary content never enters a text output
        if not is_text_file(path):
            return FileReport(path, relative, "skipped", "not a text file"), None

        # 4. Generated output, before the size limit: outputs are usually large
        size = file_size(path)
        if is_generated_file(path):
            return FileReport(path, relative, "skipped", "generated by simplibs-extractor", size), None

        # 5. Too large to be useful
        if max_size is not None and size > max_size:
            return FileReport(path, relative, "skipped", f"too large ({size} > {max_size} bytes)", size), None

        # 6. Read it
        text = read_text(path)

    # 7. A file that vanished, is locked or is not valid text fails alone; the run continues
    except (SimpleException, OSError) as exc:
        return FileReport(path, relative, "error", f"read failed: {describe_failure(exc)}"), None

    # 8. Included
    return FileReport(path, relative, "ok", None, size), text


_DESIGN_NOTES = """
# read_source — One File, One Verdict

## Purpose
The whole read phase for one file. It never raises for the file's own
problems; it returns a report, so one bad file cannot stop a run over a
thousand.

## Order of Checks
Outside the source, binary, generated, too large, read. A generated output is usually bigger than
the limit; if the size came first it would be reported as "too large", which
hides the real reason.

## Links That Lead Out
A symbolic link whose real location lies outside the source is skipped
(`points outside the source`) before anything is read: a link to a private
file must never end up in an output. The report keeps the link's own name.
Links that stay inside the source are followed as usual.

## `skipped` Versus `error`
A skipped file was left out on purpose and is not a problem. An error file
was meant to be included and could not be; it makes the run unsuccessful.

## Narrow Catch
Only library cards and OS errors are caught. A bug in this code is not
dressed up as a file problem.
"""
